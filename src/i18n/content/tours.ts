export function getTours(locale: Locale): readonly Tour[] {
  const sourceTours = placeholderTours as readonly Tour[];
  if (locale === "en") return sourceTours;
  return sourceTours.map((tour) => {
    const translated = translations[tour.slug as keyof typeof translations];
    const itinerarySource = tour.slug === "comfy-tour" ? comfyItineraryAr : discoveryItineraryAr;
    return {
      ...tour,
      ...translated,
      durationLabel: "8 أيام من الاكتشاف الكامل",
      practicalNote: "رحلة لا تُنسى عبر مناظر جزيرة سقطرى الساحرة، من أشجار دم الأخوين الشهيرة والكثبان الرملية العظيمة إلى الشواطئ البكر والكهوف والأودية والبحيرة الزرقاء الجميلة.",
      featuredImage: { ...tour.featuredImage, alt: "صورة مؤقتة لمنظر طبيعي في سقطرى تظهر أشجار دم الأخوين على هضبة صخرية." },
      pricingTiers: tour.pricingTiers?.map((tier) => ({
        ...tier,
        label: tier.minGuests === 2 ? "الأزواج" : tier.minGuests === 4 ? "4–5 أشخاص" : tier.minGuests === 6 ? "6–7 أشخاص" : "8 أشخاص أو أكثر",
      })),
      included: tour.slug === "comfy-tour" ? comfyIncludedAr : sharedIncludedAr,
      requiredExtras: extrasAr,
      itinerary: itinerarySource.map(([title, description, overnight], index) => ({
        ...tour.itinerary?.[index], day: index + 1, title, description, overnight,
      })),
    } satisfies Tour;
  });
}

export function getPublishedTour(locale: Locale, slug: string) {
  return getTours(locale).find((tour) => tour.slug === slug && tour.published);
}

